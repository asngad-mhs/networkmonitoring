// Helper to generate 20 historical data points
export const generateHistory = (baseRx: number, baseTx: number, variance = 0.15, count = 24) => {
  const now = Date.now();
  const step = 5000; // 5 seconds
  const list = [];
  for (let i = count - 1; i >= 0; i--) {
    const factor = 1 + (Math.sin(i / 2) * variance) + ((Math.random() - 0.5) * variance);
    list.push({
      timestamp: now - i * step,
      rxMbps: Number(Math.max(0.1, baseRx * factor).toFixed(2)),
      txMbps: Number(Math.max(0.1, baseTx * factor).toFixed(2)),
    });
  }
  return list;
};

export const generateSystemHistory = (baseCpu: number, baseRam: number, baseLatency: number, baseTemp: number, count = 24) => {
  const now = Date.now();
  const step = 5000;
  const list = [];
  for (let i = count - 1; i >= 0; i--) {
    const jitter = (Math.random() - 0.5) * 4;
    list.push({
      timestamp: now - i * step,
      cpu: Number(Math.min(100, Math.max(1, baseCpu + jitter)).toFixed(1)),
      ram: Number(Math.min(100, Math.max(5, baseRam + (Math.random() - 0.5) * 2)).toFixed(1)),
      latency: Number(Math.max(0.5, baseLatency + (Math.random() - 0.5) * 3).toFixed(1)),
      temp: Number((baseTemp + (Math.random() - 0.5) * 1.5).toFixed(1)),
    });
  }
  return list;
};

